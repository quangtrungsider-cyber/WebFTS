export type ProcedureType = 'SID' | 'STAR' | 'IAP' | 'HOLDING';

// icao -> procedure_type -> procedure_name -> [feature ids]
export type ProceduresIndex = Record<string, Partial<Record<ProcedureType, Record<string, string[]>>>>;

export interface ProcedureCounts {
  SID: number;
  STAR: number;
  IAP: number;
  HOLDING: number;
}

interface RawTrackFeature {
  type: 'Feature';
  properties: {
    id?: string;
    procedure_type?: ProcedureType;
    procedure_name?: string;
    airport_icao?: string;
    [key: string]: unknown;
  };
  geometry: GeoJSON.Geometry;
}

const PROCEDURE_COLOR: Record<ProcedureType, string> = {
  SID: '#16a34a', STAR: '#dc2626', IAP: '#2563eb', HOLDING: '#f59e0b',
};

let indexCache: Promise<ProceduresIndex> | null = null;
let runwayIndexCache: Promise<Record<string, { runways: Record<string, string> }>> | null = null;
const rawFeatureMapCache: Record<string, Promise<Record<string, GeoJSON.Feature>>> = {};

function getRawFeatureMap(icao: string): Promise<Record<string, GeoJSON.Feature>> {
  if (!rawFeatureMapCache[icao]) {
    // Cache-busted like getIndex()'s own procedures_index.json fetch below --
    // this file gets regenerated by the procedure rebuild tooling from time
    // to time, and an uncached-busted fetch could otherwise keep serving an
    // already-cached pre-rebuild copy until a hard refresh.
    rawFeatureMapCache[icao] = fetch(`/static/data/vatm_kmz/procedures_by_airport/vatm_procedures_${icao}.geojson?v=${Date.now()}`)
      .then(res => { if (!res.ok) throw new Error(`Failed to load procedure tracks for ${icao}`); return res.json(); })
      .then((data: { features: RawTrackFeature[] }) => {
        const map: Record<string, GeoJSON.Feature> = {};
        data.features.forEach(f => { if (f.properties.id) map[f.properties.id] = f as unknown as GeoJSON.Feature; });
        return map;
      });
  }
  return rawFeatureMapCache[icao];
}

export const proceduresIndexApi = {
  procedureColor: (type: ProcedureType) => PROCEDURE_COLOR[type],

  getIndex: (): Promise<ProceduresIndex> => {
    if (!indexCache) {
      indexCache = fetch('/static/data/vatm_kmz/procedures_index.json')
        .then(res => { if (!res.ok) throw new Error('Failed to load procedures index'); return res.json(); });
    }
    return indexCache;
  },

  countsFor: (index: ProceduresIndex, icao: string): ProcedureCounts | null => {
    const entry = index[icao];
    if (!entry) return null;
    return {
      SID: Object.keys(entry.SID || {}).length,
      STAR: Object.keys(entry.STAR || {}).length,
      IAP: Object.keys(entry.IAP || {}).length,
      HOLDING: Object.keys(entry.HOLDING || {}).length,
    };
  },

  getRunwayIndex: (): Promise<Record<string, { runways: Record<string, string> }>> => {
    if (!runwayIndexCache) {
      runwayIndexCache = fetch('/static/data/vatm_kmz/aerodromes_runways_index.json')
        .then(res => { if (!res.ok) throw new Error('Failed to load runway index'); return res.json(); });
    }
    return runwayIndexCache;
  },

  /** Fetches the airport's raw nominal-track segments and groups them into
   * one FeatureCollection per procedure type (SID/STAR/IAP/HOLDING), each
   * segment kept as its own LineString feature -- real published tracks are
   * exported as many short segments per named procedure, not one merged
   * polyline, so segments are rendered individually rather than
   * reconstructed into a single ordered route. */
  getGroupedTracks: async (icao: string): Promise<Partial<Record<ProcedureType, GeoJSON.FeatureCollection>>> => {
    const map = await getRawFeatureMap(icao);
    const grouped: Partial<Record<ProcedureType, GeoJSON.Feature[]>> = {};
    Object.values(map).forEach(f => {
      const type = (f.properties as RawTrackFeature['properties'] | null)?.procedure_type;
      if (!type) return;
      (grouped[type] ??= []).push(f);
    });
    return Object.fromEntries(
      Object.entries(grouped).map(([type, features]) => [type, { type: 'FeatureCollection', features } as GeoJSON.FeatureCollection])
    );
  },

  /** Named transitions of one procedure type for an airport (e.g. every SID
   * name at VVCA), sorted for stable list display. */
  transitionNamesFor: (index: ProceduresIndex, icao: string, type: ProcedureType): string[] =>
    Object.keys(index[icao]?.[type] || {}).sort(),

  /** Segments belonging to one named transition (e.g. VVCA's "ENRIN 2F" SID)
   * -- resolves the transition's feature-id list from procedures_index.json
   * against the airport's raw track features. Segments are real published
   * track pieces, not reconstructed into one ordered polyline, since the
   * source export has no explicit inter-segment ordering. */
  getTransitionTrack: async (index: ProceduresIndex, icao: string, type: ProcedureType, name: string): Promise<GeoJSON.FeatureCollection> => {
    const ids = index[icao]?.[type]?.[name] || [];
    const map = await getRawFeatureMap(icao);
    return { type: 'FeatureCollection', features: ids.map(id => map[id]).filter(Boolean) };
  },
};
