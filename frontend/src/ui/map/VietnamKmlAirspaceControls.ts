/**
 * Sets up and registers procedure & holding layers with high-performance filters
 * and beautiful color mapping expressions.
 */

async function setupDynamicProcedureAndHoldingLayers(map: maplibregl.Map): Promise<void> {
  let airports = ['VVTS', 'VVNB', 'VVDN'];
  try {
    const res = await fetch(`/static/data/vatm_kmz/procedures_index.json?v=${Date.now()}`);
    if (res.ok) {
        const data = await res.json();
        airports = Object.keys(data);
    }
  } catch(e) {
    console.error("Failed to fetch procedures index for map layers", e);
  }

  const dynamicSources: {id: string, data: string, type: string}[] = [
    { id: "vatm-kmz-holding", data: "/static/data/vatm_kmz/vatm_holding_areas.geojson", type: "holding" },
    { id: "vatm-kmz-acc-fir", data: "/static/data/vatm_kmz/vatm_acc_fir_sectors.geojson", type: "acc" },
    { id: "vatm-kmz-tma-ctr", data: "/static/data/vatm_kmz/vatm_tma_ctr.geojson", type: "tma" }
  ];

  // Cache-busted (like procedures_index.json's own fetch above): these
  // per-airport geojson files get regenerated by the procedure rebuild
  // tooling from time to time, and a browser that already cached an older
  // copy would otherwise keep showing stale track geometry/names after a
  // rebuild until a hard refresh -- confirmed live (querySourceFeatures
  // still returned pre-fix transition names after a normal reload, only a
  // cache-bypassing reload picked up the rebuilt file).
  const cacheBust = Date.now();
  airports.forEach(apt => {
    dynamicSources.push({
      id: `vatm-kmz-proc-${apt.toLowerCase()}`,
      data: `/static/data/vatm_kmz/procedures_by_airport/vatm_procedures_${apt}.geojson?v=${cacheBust}`,
      type: "proc"
    });
  });

  dynamicSources.forEach(src => {
    if (!map.getSource(src.id)) {
      map.addSource(src.id, { type: "geojson", data: src.data });
    }


    const emptyFilter = ["literal", false] as any;
    const isProc = src.type === "proc";

    // Define colors and styles dynamically based on source type
    let fillColorExpr: any;
    let lineColorExpr: any;
    let fillOpacityExpr: number;
    let lineWidthExpr: number;
    let lineOpacityExpr: number;

    if (src.type === "holding") {
      fillColorExpr = "#f59e0b"; // Amber
      lineColorExpr = "#f59e0b";
      fillOpacityExpr = 0.12;
      lineWidthExpr = 1.5;
      lineOpacityExpr = 0.85;
    } else if (src.type === "acc") {
      fillColorExpr = "#8b5cf6"; // Purple
      lineColorExpr = "#a78bfa";
      fillOpacityExpr = 0.06;
      lineWidthExpr = 1.5;
      lineOpacityExpr = 0.7;
    } else if (src.type === "tma") {
      fillColorExpr = "#0284c7"; // Blue
      lineColorExpr = "#38bdf8";
      fillOpacityExpr = 0.08;
      lineWidthExpr = 1.6;
      lineOpacityExpr = 0.7;
    } else {
      // Procedures
      fillColorExpr = [
        "case",
        ["in", "sid", ["downcase", ["coalesce", ["get", "folder_path"], ""]]], "#22c55e", // Emerald
        ["in", "star", ["downcase", ["coalesce", ["get", "folder_path"], ""]]], "#22d3ee", // Cyan
        ["in", "iap", ["downcase", ["coalesce", ["get", "folder_path"], ""]]], "#d946ef", // Magenta
        ["in", "holding", ["downcase", ["coalesce", ["get", "folder_path"], ""]]], "#f59e0b", // Amber (matches the dedicated holding layer)
        "#22d3ee" // Default Cyans
      ] as any;
      lineColorExpr = fillColorExpr;
      fillOpacityExpr = 0.12;
      lineWidthExpr = 1.5;
      lineOpacityExpr = 0.85;
    }

    // 1. Add Fill Layer (for protection area polygons)
    const fillId = `${src.id}-fill`;
    if (!map.getLayer(fillId)) {
      map.addLayer({
        id: fillId,
        type: "fill",
        source: src.id,
        filter: isProc ? ["literal", false] : emptyFilter,
        paint: {
          "fill-color": fillColorExpr,
          "fill-opacity": fillOpacityExpr
        }
      });
    }

    // 2. Add Line Layer (for lines and polygon outlines)
    const lineId = `${src.id}-line`;
    if (!map.getLayer(lineId)) {
      map.addLayer({
        id: lineId,
        type: "line",
        source: src.id,
        filter: isProc 
          ? ["all", emptyFilter, ["==", ["geometry-type"], "LineString"]] 
          : emptyFilter,
        paint: {
          "line-color": lineColorExpr,
          "line-width": lineWidthExpr,
          "line-opacity": lineOpacityExpr
        }
      });
    }

    // 3. Add Label Layer
    const labelId = `${src.id}-label`;
    if (!map.getLayer(labelId)) {
      const isPointPlacement = src.type === "holding" || src.type === "acc" || src.type === "tma";
      map.addLayer({
        id: labelId,
        type: "symbol",
        source: src.id,
        filter: isProc 
          ? ["all", emptyFilter, ["==", ["geometry-type"], "LineString"]] 
          : emptyFilter,
        layout: {
          "symbol-placement": isPointPlacement ? "point" : "line",
          // Procedure features (SID/STAR/IAP) carry a real "procedure_name"
          // (e.g. "NUMDI") -- preferred over "name", which is the raw KML
          // leg-folder label (ARINC-424 "A-B" pair, e.g. "TIHAN-PQ704") and
          // reads as noise on the map. Non-procedure sources (airways,
          // sectors, holding) have no procedure_name, so they fall through
          // to "name"/"id" unchanged.
          "text-field": ["coalesce", ["get", "procedure_name"], ["get", "name"], ["get", "id"], ""] as any,
          "text-size": (src.type === "holding"
            ? ["interpolate", ["linear"], ["zoom"], 7, 0, 8.5, 8.5]
            : 8.5) as any,
          "text-allow-overlap": false
        },
        paint: {
          "text-color": "#ffffff",
          "text-halo-color": "#090d16",
          "text-halo-width": 2.0
        }
      });
      
      // Set zoom constraints dynamically for crisp details
      map.setLayerZoomRange(labelId, isPointPlacement ? 7.5 : 8.5, 24);
    }
  });

  // Manually add Aerodromes
  if (!map.getSource("vatm-kmz-aerodromes")) {
      map.addSource("vatm-kmz-aerodromes", { type: "geojson", data: "/static/data/vatm_kmz/vatm_aerodromes.geojson" });
  }
  const emptyFilter = ["in", ["get", "id"], ["literal", []]] as any;
  if (!map.getLayer("vatm-kmz-aerodromes-circle")) {
      map.addLayer({
          id: "vatm-kmz-aerodromes-circle",
          type: "circle",
          source: "vatm-kmz-aerodromes",
          filter: emptyFilter,
          paint: {
              "circle-radius": 4.5,
              "circle-color": "#facc15",
              "circle-stroke-color": "#020617",
              "circle-stroke-width": 1.5
          }
      });
  }
  if (!map.getLayer("vatm-kmz-aerodromes-label")) {
      map.addLayer({
          id: "vatm-kmz-aerodromes-label",
          type: "symbol",
          source: "vatm-kmz-aerodromes",
          filter: emptyFilter,
          layout: {
              "symbol-placement": "point",
              "text-field": ["get", "name"],
              "text-size": 11,
              "text-offset": [0, 1.2],
              "text-allow-overlap": false
          },
          paint: {
              "text-color": "#ffffff",
              "text-halo-color": "#000000",
              "text-halo-width": 2.0
          }
      });
  }

  // Manually add Runways
  if (!map.getSource("vatm-kmz-runways")) {
      map.addSource("vatm-kmz-runways", { type: "geojson", data: "/static/data/vatm_kmz/vatm_runways.geojson" });
  }
  if (!map.getLayer("vatm-kmz-runways-line")) {
      map.addLayer({
          id: "vatm-kmz-runways-line",
          type: "line",
          source: "vatm-kmz-runways",
          filter: emptyFilter,
          paint: {
              "line-color": "#ffffff",
              "line-width": 3.0,
              "line-opacity": 0.9
          }
      });
  }
  if (!map.getLayer("vatm-kmz-runways-label")) {
      map.addLayer({
          id: "vatm-kmz-runways-label",
          type: "symbol",
          source: "vatm-kmz-runways",
          filter: emptyFilter,
          layout: {
              "symbol-placement": "line",
              "text-field": ["get", "name"],
              "text-size": 10,
              "text-offset": [0, -1],
              "text-allow-overlap": false
          },
          paint: {
              "text-color": "#ffffff",
              "text-halo-color": "#000000",
              "text-halo-width": 2.0
          }
      });
  }
}

/**
 * Public high-performance filter updater called by the Accordion Tree selection handler.
 */

let globalActiveAirspaceIds: Set<string> = new Set();
let globalActiveProcedureIds: Set<string> = new Set();
let globalActiveAerodromeIds: Set<string> = new Set();

export function setAirspaceBoundaryIds(map: maplibregl.Map, ids: string[]): void {
    globalActiveAirspaceIds = new Set(ids);
    applyActiveFilters(map);
}

export function setProcedureIds(map: maplibregl.Map, ids: string[]): void {
    globalActiveProcedureIds = new Set(ids);
    applyActiveFilters(map);
}

export function setAerodromeIds(map: maplibregl.Map, ids: string[]): void {
    globalActiveAerodromeIds = new Set(ids);
    applyActiveFilters(map);
}



export function updateActiveAirspaceFilters(map: maplibregl.Map, activeIds: string[]): void {
    // Legacy support for AirspaceDataPanel which passes boundary IDs here
    setAirspaceBoundaryIds(map, activeIds);
}

function applyActiveFilters(map: maplibregl.Map): void {
  const allActiveIds = [...Array.from(globalActiveAirspaceIds), ...Array.from(globalActiveProcedureIds), ...Array.from(globalActiveAerodromeIds)];

  console.log('[VietnamKmlAirspaceControls] applyActiveFilters called, allActiveIds=', allActiveIds);

  // We need to know all airport source IDs to update them
  const dynamicSourceIds = [
    "vatm-kmz-holding",
    "vatm-kmz-acc-fir",
    "vatm-kmz-tma-ctr",
    "vatm-kmz-aerodromes",
    "vatm-kmz-runways"
  ];

  // Find all proc sources dynamically
  const style = map.getStyle();
  if (style && style.sources) {
      Object.keys(style.sources).forEach(src => {
          if (src.startsWith("vatm-kmz-proc-") && !dynamicSourceIds.includes(src)) {
              dynamicSourceIds.push(src);
          }
      });
  }

  // Use ["match"] instead of ["in"] — more reliable across MapLibre GL JS 4.x/5.x,
  // and avoids potential type-inference issues with ["in", expr, ["literal", []]].
  const filterExpr: any = allActiveIds.length > 0
      ? ["match", ["get", "id"], allActiveIds, true, false]
      : ["literal", false];

  console.log('[VietnamKmlAirspaceControls] filterExpr=', JSON.stringify(filterExpr));

  dynamicSourceIds.forEach(srcId => {

    const isProc = srcId.startsWith("vatm-kmz-proc-");
    ["fill", "line", "circle", "label"].forEach(suffix => {
      const layerId = `${srcId}-${suffix}`;
      const layerExists = !!map.getLayer(layerId);
      if (layerExists) {
        try {
          if (isProc) {
            if (suffix === "fill") {
              map.setFilter(layerId, ["literal", false]);
            } else {
              const combinedFilter = [
                "all",
                filterExpr,
                ["==", ["geometry-type"], "LineString"]
              ] as any;
              map.setFilter(layerId, combinedFilter);
            }
          } else {
            map.setFilter(layerId, filterExpr);
          }
        } catch (e) {
          console.error('[VietnamKmlAirspaceControls] setFilter error on', layerId, e);
        }
      } else if (srcId === 'vatm-kmz-acc-fir' || srcId === 'vatm-kmz-tma-ctr') {
        console.warn('[VietnamKmlAirspaceControls] layer NOT found:', layerId);
      }
    });
  });
}

function addSourceAndLayers(map: maplibregl.Map, groupKey: string, s: SourceDef): void {
  if (!map.getSource(s.id)) {
    map.addSource(s.id, { type: "geojson", data: s.data });
  }

  if (s.geom === "fill") {
    const fillId = `${s.id}-fill`;
    if (!map.getLayer(fillId)) {
      map.addLayer({
        id: fillId,
        type: "fill",
        source: s.id,
        paint: {
          "fill-color": fillColorFor(s.id),
          "fill-opacity": fillOpacityFor(s.id)
        }
      });
    }

    const lineId = `${s.id}-line`;
    if (!map.getLayer(lineId)) {
      map.addLayer({
        id: lineId,
        type: "line",
        source: s.id,
        paint: {
          "line-color": outlineColorFor(s.id),
          "line-width": outlineWidthFor(s.id),
          "line-opacity": outlineOpacityFor(s.id)
        }
      });
    }

    addLabelLayer(map, s.id, false);
  } else if (s.geom === "line") {
    const lineId = `${s.id}-line`;
    if (!map.getLayer(lineId)) {
      map.addLayer({
        id: lineId,
        type: "line",
        source: s.id,
        paint: {
          "line-color": lineColorFor(s.id),
          "line-width": lineWidthFor(s.id),
          "line-opacity": lineOpacityFor(s.id)
        }
      });
    }

    addLabelLayer(map, s.id, true);
  } else if (s.geom === "circle") {
    const circleId = `${s.id}-circle`;
    if (!map.getLayer(circleId)) {
      map.addLayer({
        id: circleId,
        type: "circle",
        source: s.id,
        paint: {
          "circle-radius": 3.2,
          "circle-color": "#facc15",
          "circle-stroke-color": "#020617",
          "circle-stroke-width": 1.2
        }
      });
    }

    addLabelLayer(map, s.id, false, true);
  }
}

function addLabelLayer(map: maplibregl.Map, sourceId: string, line = false, zoomDependent = false): void {
  const labelId = `${sourceId}-label`;
  if (map.getLayer(labelId)) return;

  map.addLayer({
    id: labelId,
    type: "symbol",
    source: sourceId,
    layout: {
      ...(line ? { "symbol-placement": "line" } : {}),
      "text-field": ["coalesce", ["get", "name"], ["get", "id"], ""],
      "text-size": zoomDependent
        ? ["interpolate", ["linear"], ["zoom"], 7, 0, 9.5, 9.5]
        : 8.5,
      "text-allow-overlap": false
    },
    paint: {
      "text-color": "#e2e8f0",
      "text-halo-color": "#090d16",
      "text-halo-width": 2.0
    }
  });
}

function ensureGroupVisibility(map: maplibregl.Map, group: GroupDef, visible: boolean): void {
  group.active = visible;

  if (visible) {
    group.sources.forEach(s => addSourceAndLayers(map, group.key, s));
  }

  group.sources.forEach(s => {
    ["fill", "line", "circle", "label"].forEach(suffix => {
      const id = `${s.id}-${suffix}`;
      if (map.getLayer(id)) {
        map.setLayoutProperty(id, "visibility", visible ? "visible" : "none");
      }
    });
  });
}

