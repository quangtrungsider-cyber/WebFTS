// Global reference for active map instance
let activeMapInstance: maplibregl.Map | null = null;

export function installVietnamKmlAirspaceControls(map: maplibregl.Map): void {
  activeMapInstance = map;

  const setupOnStyleLoad = () => {
    // 1. Re-create active static groups
    GROUPS.forEach(g => {
      if (g.active) {
        g.sources.forEach(s => addSourceAndLayers(map, g.key, s));
        ensureGroupVisibility(map, g, true);
      }
    });

    // 2. Pre-initialize and register procedures, holdings, and boundaries (initially filtered to empty)
    setupDynamicProcedureAndHoldingLayers(map).then(() => {
      // Load and apply saved boundary and procedure filter selections after layers are successfully created
      applySavedSectorsAndProcedures(map);
      
      // Load and apply saved aerodrome layouts
      try {
        const savedAero = localStorage.getItem('webfts_checked_aerodrome_layouts');
        if (savedAero) {
          const arr = JSON.parse(savedAero);
          if (Array.isArray(arr) && arr.length > 0) {
            import('./AerodromeLayoutLayer').then(m => {
              m.setAerodromeLayoutIds(map, arr);
            });
          }
        } else {
            import('./AerodromeLayoutLayer').then(m => {
              m.setAerodromeLayoutIds(map, ['VVNB', 'VVTS', 'VVDN']);
            });
        }
      } catch (e) {
        console.error("Failed to restore aerodrome layouts", e);
      }
    });

    // 3. Create the floating overlay toolbar
    createVatmOverlayToolbar(map);
  };

  map.on("style.load", setupOnStyleLoad);

  if (map.loaded()) {
    setupOnStyleLoad();
  }
}

