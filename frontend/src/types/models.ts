/** Superset of what either structured source publishes per leg. The RNAV2
 * draft (.docx) and the ENR3.1 legacy AIP (.pdf) don't publish quite the same
 * fields -- e.g. ENR3.1 gives airspace class/width/RNP/reverse-track but never
 * an odd/even cruising-level split, while the RNAV2 draft is the other way
 * around -- so fields either source doesn't have are simply null/absent
 * rather than invented. */
export interface AirwaySegment {
  seq: number;
  fromWaypoint: string;
  toWaypoint: string;
  magneticTrackDeg: number | null;
  reverseMagneticTrackDeg?: number | null;
  distanceKm: number | null;
  upperLimit: AirwayVerticalLimit | null;
  lowerLimit: AirwayVerticalLimit | null;
  minSafeAltitudeM: number | null;
  lateralLimit?: AirwayLateralLimit | null;
  widthKm?: number | null;
  airspaceClass?: string | null;
  navAccuracy?: string | null;
  cruisingLevels: 'odd' | 'even' | null;
  usageConditions: string | null;
}

/** A fully parsed airway: ordered waypoint chain + per-leg constraints.
 * `rnav2Draft` comes from `airways_rnav2_draft.json` (Phase 1, 6 draft
 * routes); `enr31Legacy` comes from `airways_enr31_legacy.json` (Phase 2, 54
 * official AIP routes). The remaining ~20 legacy routes (mostly Q-series
 * RNAV routes, published in a different AIP chapter that wasn't supplied)
 * have no structured source and fall back to per-segment raw AIP params. */
export interface StructuredAirway {
  code: string;
  navigationSpec: string | null;
  waypointCount: number;
  segmentCount: number;
  waypoints: AirwayWaypoint[];
  segments: AirwaySegment[];
  sourceKind: 'rnav2Draft' | 'enr31Legacy';
}

/** Per-segment AIP parameters already embedded (as a flat, unparsed string)
 * in every legacy route feature's `description` property. Parsed client-side
 * -- see `airwaysApi.parseLegacyParams`. Populated for the 74 legacy AIP
 * routes that don't yet have a Phase-2 structured waypoint chain. */
export interface AirwayLegacyParam {
  featureId: string;
  fid: string | null;
  lastModified: string | null;
  upperLimit: AirwayVerticalLimit | null;
  lowerLimit: AirwayVerticalLimit | null;
  minSafeAltitudeM: number | null;
  widthKm: number | null;
  routeType: string | null;
  rnp: number | null;
  magneticTrackDeg: number | null;
  reverseMagneticTrackDeg: number | null;
  lengthKm: number | null;
  airspaceClass: string | null;
  domIntl: string | null;
}

