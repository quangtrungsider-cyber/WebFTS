// Real SID/STAR-mix capacity-test scenario, generated by
// capacity_scenario_engine.py from an airport's published procedure data
// (see GET /api/airports/<icao>/procedures for the transition names and
// default mix each registered airport supports).
export interface CapacityScenarioConfig {
  sidMix: Record<string, number>;
  starMix: Record<string, number>;
  hours: number;
  seed: number;
  asasOn: boolean;
  minArrArrGapSec: number;
  depAfterArrGapSec: number;
  minRunwayGapSec: number;
  /** Shifts the whole generated schedule so the first event lands at t=0
   * instead of wherever the hourly scheduler placed it (e.g. a lone
   * arrival otherwise spawns ~15-20min into the scenario). Used by the
   * single-aircraft "simple scenario" builder; leave unset/false for real
   * capacity-mix scenarios where within-the-hour timing matters. */
  alignFirstSpawnToZero?: boolean;
}

